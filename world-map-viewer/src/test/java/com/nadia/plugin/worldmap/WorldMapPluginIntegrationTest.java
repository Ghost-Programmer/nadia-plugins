package com.nadia.plugin.worldmap;

import com.nadia.app.plugin.api.NadiaPluginContext;
import com.nadia.app.plugin.api.PluginDockableDescriptor;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.pf4j.PluginWrapper;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.anyList;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

public class WorldMapPluginIntegrationTest {

    @AfterEach
    public void tearDown() {
        WorldMapRuntime.shutdownCurrent();
    }

    @Test
    public void testPluginLifecycleAssetExtractionUiDescriptorAndExtensionsIdx(@TempDir Path tempDir) throws Exception {
        NadiaPluginContext context = mock(NadiaPluginContext.class);
        when(context.getPluginDataDir(WorldMapRuntime.PLUGIN_ID)).thenReturn(tempDir);

        PluginWrapper wrapper = mock(PluginWrapper.class);
        when(wrapper.getPluginId()).thenReturn(WorldMapRuntime.PLUGIN_ID);

        WorldMapPlugin plugin = new WorldMapPlugin(wrapper);
        plugin.setPluginContext(context);
        plugin.start();

        // 1. Verify required nadia.prop.* keys are registered
        verify(context, atLeastOnce()).registerProperties(anyList(), eq("Plugin: " + WorldMapRuntime.PLUGIN_ID));

        // 2. Verify map.html, leaflet.js, and leaflet.css were extracted into pluginDataDir
        assertTrue(Files.isRegularFile(tempDir.resolve("map.html")));
        assertTrue(Files.isRegularFile(tempDir.resolve("leaflet.js")));
        assertTrue(Files.isRegularFile(tempDir.resolve("leaflet.css")));
        assertNotNull(WorldMapRuntime.getOrCreate(context).getExtractedMapHtmlUri());

        // 3. Verify WorldMapUiExtension contributes dockable "map"
        WorldMapUiExtension uiExt = new WorldMapUiExtension();
        Optional<PluginDockableDescriptor> dockableOpt = uiExt.createDockableWindow(context);
        assertTrue(dockableOpt.isPresent());
        assertEquals("map", dockableOpt.get().id());
        assertTrue(dockableOpt.get().title().contains("World Map Viewer"));

        // 4. Verify PF4J annotation processor generated META-INF/extensions.idx containing all 5 extensions
        try (InputStream is = getClass().getClassLoader().getResourceAsStream("META-INF/extensions.idx")) {
            assertNotNull(is, "META-INF/extensions.idx must be generated by PF4J annotation processor");
            String idx = new String(is.readAllBytes(), StandardCharsets.UTF_8);
            List<String> expectedExtensions = List.of(
                    "com.nadia.plugin.worldmap.WorldMapUiExtension",
                    "com.nadia.plugin.worldmap.tool.MapTool",
                    "com.nadia.plugin.worldmap.tool.AviationTool",
                    "com.nadia.plugin.worldmap.tool.SatelliteTool",
                    "com.nadia.plugin.worldmap.tool.EarthquakeTool"
            );
            for (String extName : expectedExtensions) {
                assertTrue(idx.contains(extName), "META-INF/extensions.idx must list " + extName);
            }
        }

        plugin.stop();
    }
}
